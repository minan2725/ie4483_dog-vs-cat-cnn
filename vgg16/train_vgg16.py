"""Train a VGG16 classifier on Dogs vs Cats.

The dataset path is the DATA_DIR constant at the top of preprocessing.py (repository root).
Every run writes into its OWN folder vgg16/runs/<auto-generated-name>/ so nothing is overwritten.

Run it from the repository root (the folder that contains preprocessing.py):
    python3 vgg16/train_vgg16.py --train-per-class 200 --val-per-class 100 --epochs 1   # smoke test
    python3 vgg16/train_vgg16.py                                                        # baseline
    python3 vgg16/train_vgg16.py --lr 1e-3
    python3 vgg16/train_vgg16.py --freeze-backbone --lr 1e-3
    python3 vgg16/train_vgg16.py --no-augment
    python3 vgg16/train_vgg16.py --img-size 128
    python3 vgg16/train_vgg16.py --scratch --lr 1e-3 --epochs 10
"""
import argparse
import csv
import json
import sys
import time
from pathlib import Path

import torch
import torch.nn as nn
from torch.utils.data import DataLoader
from torchvision import models

HERE = Path(__file__).resolve().parent         # this folder (vgg16/)
sys.path.insert(0, str(HERE.parent))           # repository root, where preprocessing.py lives
from preprocessing import DATA_DIR, TestImages, get_device, get_loaders, set_seed  # noqa: E402

RUNS_DIR = HERE / "runs"

def build_model(freeze_backbone, scratch):
    # scratch=True -> random initialisation; otherwise ImageNet-pretrained weights.
    weights = None if scratch else models.VGG16_Weights.IMAGENET1K_V1
    model = models.vgg16(weights=weights)
    if freeze_backbone:
        for p in model.parameters():
            p.requires_grad = False
    # New classification head: 2048 features -> 2 classes (cat, dog).
    # Created after freezing, so it is always trainable.
    model.classifier[6] = nn.Linear(model.classifier[6].in_features, 2)
    return model


def run_epoch(model, loader, criterion, device, optimizer=None):
    training = optimizer is not None
    model.train(training)
    total_loss, correct, n = 0.0, 0, 0
    with torch.set_grad_enabled(training):
        for images, labels in loader:
            images, labels = images.to(device), labels.to(device)
            outputs = model(images)
            loss = criterion(outputs, labels)
            if training:
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()
            total_loss += loss.item() * images.size(0)
            correct += (outputs.argmax(1) == labels).sum().item()
            n += images.size(0)
    return total_loss / n, correct / n


@torch.no_grad()
def predict_test(model, test_dir, device, args, out_dir):
    model.eval()
    loader = DataLoader(TestImages(test_dir, args.img_size), batch_size=args.batch_size,
                        shuffle=False, num_workers=args.num_workers)
    rows = []
    for images, names in loader:
        probs = torch.softmax(model(images.to(device)), dim=1).cpu()
        for name, p in zip(names, probs):
            rows.append((Path(name).stem, int(p.argmax()), float(p[0]), float(p[1])))
    # NOTE: check the sample submission.csv from the course and adapt the ID / header format if needed.
    with open(out_dir / "submission.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "label"])  # label: 1 = dog, 0 = cat
        w.writerows((r[0], r[1]) for r in rows)
    # Probabilities help with error analysis (low-confidence images are the interesting ones).
    with open(out_dir / "test_probs.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "pred", "prob_cat", "prob_dog"])
        w.writerows(rows)
    print(f"Wrote {len(rows)} predictions to {out_dir / 'submission.csv'}")


def default_run_name(args):
    parts = ["vgg16", f"lr{args.lr:g}", f"n{args.train_per_class}",
             f"e{args.epochs}", f"s{args.seed}"]
    if args.freeze_backbone:
        parts.append("frozen")
    if args.no_augment:
        parts.append("noaug")
    if args.scratch:
        parts.append("scratch")
    if args.img_size != 224:
        parts.append(f"img{args.img_size}")
    return "_".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--train-per-class", type=int, default=5000)
    ap.add_argument("--val-per-class", type=int, default=0, help="0 = use all validation images")
    ap.add_argument("--epochs", type=int, default=5)
    ap.add_argument("--lr", type=float, default=1e-4)
    ap.add_argument("--batch-size", type=int, default=32)
    ap.add_argument("--freeze-backbone", action="store_true", help="train only the final layer")
    ap.add_argument("--scratch", action="store_true", help="random init instead of ImageNet weights")
    ap.add_argument("--no-augment", action="store_true", help="disable training augmentation")
    ap.add_argument("--img-size", type=int, default=224)
    ap.add_argument("--num-workers", type=int, default=4)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out-dir", default=None, help="default: vgg16/runs/<auto name from the settings>")
    ap.add_argument("--overwrite", action="store_true", help="allow reusing a non-empty out-dir")
    args = ap.parse_args()
    if args.scratch and args.freeze_backbone:
        ap.error("--scratch and --freeze-backbone cannot be combined")

    out_dir = Path(args.out_dir) if args.out_dir else RUNS_DIR / default_run_name(args)
    if out_dir.exists() and any(out_dir.iterdir()) and not args.overwrite:
        ap.error(f"{out_dir} already has results. Change a setting, pick another --out-dir, "
                 f"or pass --overwrite.")
    out_dir.mkdir(parents=True, exist_ok=True)
    print("Run folder:", out_dir)

    set_seed(args.seed)
    device = get_device()
    print("Device:", device)

    train_loader, val_loader = get_loaders(
        train_per_class=args.train_per_class,
        val_per_class=args.val_per_class or None,
        batch_size=args.batch_size,
        num_workers=args.num_workers,
        img_size=args.img_size,
        augment=not args.no_augment)
    print(f"Train images: {len(train_loader.dataset)}, val images: {len(val_loader.dataset)}")

    model = build_model(args.freeze_backbone, args.scratch).to(device)
    trainable = [p for p in model.parameters() if p.requires_grad]
    n_trainable = sum(p.numel() for p in trainable)
    criterion = nn.CrossEntropyLoss()
    optimizer = torch.optim.AdamW(trainable, lr=args.lr, weight_decay=1e-4)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)

    history, best_acc, best_epoch = [], 0.0, 0
    for epoch in range(1, args.epochs + 1):
        t0 = time.time()
        tr_loss, tr_acc = run_epoch(model, train_loader, criterion, device, optimizer)
        va_loss, va_acc = run_epoch(model, val_loader, criterion, device)
        scheduler.step()
        secs = time.time() - t0
        history.append(dict(epoch=epoch, train_loss=tr_loss, train_acc=tr_acc,
                            val_loss=va_loss, val_acc=va_acc, time_s=secs))
        print(f"Epoch {epoch}/{args.epochs} | train loss {tr_loss:.4f} acc {tr_acc:.4f} | "
              f"val loss {va_loss:.4f} acc {va_acc:.4f} | {secs:.0f}s")
        if va_acc > best_acc:
            best_acc, best_epoch = va_acc, epoch
            torch.save(model.state_dict(), out_dir / "best.pt")

    summary = dict(args=vars(args), device=str(device),
                   train_images=len(train_loader.dataset), val_images=len(val_loader.dataset),
                   trainable_params=n_trainable, best_val_acc=best_acc, best_epoch=best_epoch,
                   history=history)
    with open(out_dir / "history.json", "w") as f:
        json.dump(summary, f, indent=2)
    print(f"Best validation accuracy: {best_acc:.4f} (epoch {best_epoch})")

    test_dir = DATA_DIR / "test"
    if test_dir.exists():
        model.load_state_dict(torch.load(out_dir / "best.pt", map_location=device))
        predict_test(model, test_dir, device, args, out_dir)


if __name__ == "__main__":  # this guard is required on macOS when num_workers > 0
    main()